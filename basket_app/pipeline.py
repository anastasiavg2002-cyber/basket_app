# MAIN PIPELINE
# =========================

def run_pipeline(
    projects_zip_path,
    reference_path,
    config_path
):

    # CLEAN
    shutil.rmtree("projects", ignore_errors=True)
    shutil.rmtree("results", ignore_errors=True)

    Path("projects").mkdir(exist_ok=True)
    Path("results").mkdir(exist_ok=True)

    # EXTRACT PROJECTS
    with zipfile.ZipFile(projects_zip_path, 'r') as zip_ref:

        zip_ref.extractall("projects")

    # CONFIG
    config = pd.read_excel(config_path)

    rename_map = dict(
        zip(config["original"], config["rename"])
    )

    order_map = dict(
        zip(config["rename"], config["order"])
    )

    # REFERENCE
    ref_df = pd.read_excel(
        reference_path,
        sheet_name="Список"
    )

    valid_values = set(
        ref_df.iloc[:,0]
        .dropna()
        .astype(str)
    )

    base_path = Path("projects")

    result_path = Path("results")

    # PROCESS PROJECTS
    project_folders = []

    for path in base_path.rglob("*"):

        if path.is_dir():

            excel_files = list(path.glob("*.xlsx"))

            if len(excel_files) > 0:

                project_folders.append(path)

    for project_folder in project_folders:

        if project_folder.is_dir():

            sheets = []

            for file in project_folder.glob("*.xlsx"):

                df = pd.read_excel(file)

                original = file.stem.split("_")[-1]

                sheet_name = rename_map.get(
                    original,
                    original
                )

                order = order_map.get(
                    sheet_name,
                    999
                )

                processed_df = process_sheet(
                    df,
                    valid_values
                )

                sheets.append(
                    (
                        sheet_name,
                        order,
                        processed_df
                    )
                )

            sheets = sorted(
                sheets,
                key=lambda x: x[1]
            )

            output_file = (
                result_path /
                f"Basket Analysis_{project_folder.name}.xlsx"
            )

            with pd.ExcelWriter(
                output_file,
                engine="openpyxl"
            ) as writer:

                for sheet_name, _, df in sheets:

                    df.to_excel(
                        writer,
                        sheet_name=sheet_name,
                        index=False
                    )

            apply_formatting(output_file)

    # ZIP RESULTS
    output_zip = "results.zip"

    with zipfile.ZipFile(
        output_zip,
        'w',
        zipfile.ZIP_DEFLATED
    ) as zipf:

        for file in result_path.glob("*.xlsx"):

            zipf.write(
                file,
                arcname=file.name
            )

    return output_zip